const curriculumPanel = document.getElementById('curriculumPanel');
const curriculumTrigger = document.getElementById('curriculumContext');
const curriculumBook = document.getElementById('curriculumBook');

for (const [label, provisional] of [['Taalrouteboeken', false], ['Alfa A - C (AlfaBeta+)', true]]) {
  const group = document.createElement('optgroup');
  group.label = label;
  for (const book of TAALROUTE_CURRICULUM.filter(item => item.id.startsWith('alfa-') === provisional)) {
    group.append(new Option(book.title + (provisional ? '' : ' · ' + book.level), book.id));
  }
  curriculumBook.append(group);
}
curriculumBook.value = 'zelfverzekerd';

function renderCurriculumBook() {
  const book = TAALROUTE_CURRICULUM.find(item => item.id === curriculumBook.value);
  const list = document.getElementById('curriculumThemes');
  const status = document.getElementById('curriculumStatus');
  const note = document.getElementById('curriculumNote');
  list.replaceChildren();
  status.textContent = !book?.themes.length ? 'Nog niet beschikbaar' : book.provisional ? 'Voorlopige thema-indeling' : 'Themaoverzicht';
  status.classList.toggle('provisional', !!book?.provisional);
  note.textContent = !book?.themes.length ? 'Er is nog geen complete themalijst beschikbaar in dit overzicht.' : book.note || '';
  note.hidden = !note.textContent;
  list.classList.remove('curriculum-domains');
  for (const [index, title] of (book?.themes || []).entries()) {
    const item = document.createElement('li');
    const name = document.createElement('span');
    name.textContent = title;
    item.append(name);
    if (book.focus) {
      const focus = document.createElement('small');
      focus.textContent = book.focus[index];
      item.append(focus);
    }
    list.append(item);
  }
}
curriculumBook.addEventListener('change', renderCurriculumBook);
curriculumPanel.addEventListener('toggle', () => {
  curriculumTrigger.setAttribute('aria-expanded', String(curriculumPanel.matches(':popover-open')));
});
renderCurriculumBook();
