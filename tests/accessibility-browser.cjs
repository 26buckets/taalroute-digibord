const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const {chromium,firefox,webkit}=require('playwright'),header=require('./header-actions.cjs');
const engine=process.env.TEST_ENGINE||'webkit',out=process.env.A11Y_OUTPUT||path.resolve(__dirname,'../../safari-accessibility-20261111',engine);
fs.mkdirSync(out,{recursive:true});
(async()=>{
 const browser=await ({chromium,firefox,webkit}[engine]).launch(engine==='chromium'?{channel:'chrome'}:engine==='firefox'&&process.env.FIREFOX_PATH?{executablePath:process.env.FIREFOX_PATH}:{});
 try{
  const page=await browser.newPage({viewport:{width:1440,height:1000},reducedMotion:'reduce'}),errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  await page.goto(process.env.LIVE_URL||'http://127.0.0.1:8192/',{waitUntil:'domcontentloaded'});
  await page.locator('[data-main=practice]').waitFor();
  await page.waitForFunction(()=>window.AppNavigation);
  const stable=async()=>{await page.waitForFunction(()=>!gameIsBusy());await page.waitForTimeout(150)};
  const shot=async name=>{await page.locator('#toast.show').waitFor({state:'detached'});await page.screenshot({path:path.join(out,name+'.png')});};
  await page.keyboard.press('Tab');
  assert.equal(await page.locator('.skip-content').evaluate(e=>e===document.activeElement),true);
  await shot('naar-inhoud-desktop');
  await page.keyboard.press('Enter');
  assert.equal(await page.getByRole('main').evaluate(e=>e===document.activeElement),true);
  assert.equal(new URL(page.url()).hash,'#/spelen','skip link must not change the lesson route');
  await page.locator('.taalroute-suite>summary').click();
  assert(await page.locator('.taalroute-suite-links a').first().isVisible());
  assert(await page.locator('.taalroute-suite-links img').evaluateAll(es=>es.every(e=>e.getAttribute('aria-hidden')==='true')));
  await page.locator('.taalroute-suite>summary').press('Escape');
  await header(page,'[data-main=practice]','click');
  assert.match(await page.locator('#navigationStatus').innerText(),/Maak je les klaar/);
  await page.locator('[data-browse-family=quick]').click();
  await page.locator('[data-choose-topic=vertel]').click();
  await page.locator('label:has([name=level][value=A1_A2])').click();
  await shot('les-maken-desktop');
  await page.locator('#practiceStart').click();await stable();
  const first=await page.locator('#navigationStatus').innerText();assert.match(first,/1 van/);
  await page.locator('#primaryGame').click();await stable();
  assert.match(await page.locator('#navigationStatus').innerText(),/2 van/);
  const card=await page.locator('[data-content-item-id]').first().getAttribute('data-content-item-id');
  const saved=await page.evaluate(()=>({session:ContentRuntime.activeSession(),participants:settingsState().participants,groups:settingsState().groupCount}));
  await page.locator('#cardOverview').click();
  assert(await page.getByRole('dialog',{name:'Bekeken opdrachten',exact:true}).isVisible());
  await shot('overzicht-desktop');
  await page.keyboard.press('Escape');
  await page.waitForFunction(()=>document.activeElement===document.querySelector('#cardOverview'),{},{timeout:3000});
  await header(page,'#settingsBtn','click');
  const settings=()=>page.frames().find(f=>f.url().includes('/settings/index.html'));await page.getByRole('dialog',{name:'Instellingen',exact:true}).waitFor();await settings().locator('.back-btn').waitFor();
  await page.getByRole('dialog',{name:'Instellingen',exact:true}).waitFor();
  await shot('instellingen-desktop');
  await settings().locator('.back-btn').click();await stable();
  assert.deepEqual(await page.evaluate(()=>({session:ContentRuntime.activeSession(),participants:settingsState().participants,groups:settingsState().groupCount})),saved);
  await header(page,'[data-main=play]','click');
  await page.locator('[data-nav-resume]').click();await stable();
  assert.equal(await page.locator('[data-content-item-id]').first().getAttribute('data-content-item-id'),card);
  await page.locator('#previousCard').click();await stable();assert.match(await page.locator('#navigationStatus').innerText(),/1 van/);
  await page.locator('#primaryGame').click();await stable();
  assert(await page.locator('.game-card-back').evaluate(e=>getComputedStyle(e).visibility==='hidden'),'idle card back cannot cover the exercise');
  await shot('snelvragen-desktop');
  for(const width of [390,320]){
   await page.setViewportSize({width,height:844});await stable();
   assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),'no horizontal page overflow');
   assert(await page.locator('.card-content').evaluate(e=>e.clientHeight>100),'card remains readable');
   await shot('snelvragen-'+width);
   await header(page,'#settingsBtn','click');await page.getByRole('dialog',{name:'Instellingen',exact:true}).waitFor();await settings().locator('.back-btn').waitFor();
   await shot('instellingen-'+width);
   await settings().locator('.back-btn').click();await stable();
   assert.equal(await page.locator('[data-content-item-id]').first().getAttribute('data-content-item-id'),card);
  }
  assert.deepEqual(errors,[]);
  fs.writeFileSync(path.join(out,'accessibility-tree.txt'),await page.locator('body').ariaSnapshot());
  fs.writeFileSync(path.join(out,'checks.json'),JSON.stringify({status:'PASS',engine,version:browser.version(),source:page.url(),checks:['keyboard skip link, focus and unchanged route','named main and dialogs','decorative app images excluded','screen/card status updates','ordinary public start-next-previous-menu-resume flow','settings preserve session and groups','desktop and 320/390px, no overflow'],errors,limit:'Automated browser/DOM checks, not a spoken screenreader test or physical iPhone test.'},null,2));
  console.log('PASS accessibility: '+engine+' public flows, keyboard, landmarks, dialogs, status, retained lesson/groups, desktop/mobile.');
 }finally{await browser.close()}
})().catch(e=>{console.error(e);process.exitCode=1});
